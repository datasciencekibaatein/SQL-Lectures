use company;

-- TO SELECT ALL COLUMNS
SELECT
	* 
FROM EMPLOYEES;

-- TO SELECT SPECIFIC COLUMNS
SELECT 
	EMP_NAME,
    DEPARTMENT,
    SALARY
FROM 
	EMPLOYEES;
    
    
-- DISTINCT
SELECT DISTINCT
	DEPARTMENT
FROM EMPLOYEES;



-- ALIAS(AS)
SELECT
	EMP_NAME AS NAME
FROM EMPLOYEES;


SELECT * FROM EMPLOYEES;

SELECT
	EMP_NAME,
    SALARY,
    SALARY* EXPERIENCE * 0.1 AS SALARY_HIKE
FROM EMPLOYEES;
    
    
-- FILTER ROWS
SELECT
	EMP_NAME,
    CITY,
    SALARY,
    DEPARTMENT
FROM EMPLOYEES
WHERE DEPARTMENT != "IT";

-- COMPARISION OPERATORS
-- =, != , <, >, <=, >=

-- RECORDS WHERE SALARY >= 50000
SELECT 
	*
FROM EMPLOYEES 
WHERE SALARY >=50000;

-- LOGICAL OPERATORS
-- AND, OR, NOT


-- Show records where salary>=50000 and department = IT

SELECT
	*
FROM EMPLOYEES 
WHERE 
	SALARY >= 50000 
	AND 
    DEPARTMENT = "IT";
    
-- SHOW THE RECORDS EITHER SALARY>= 50000 OR DEPARTMENT = IT

SELECT
	*
FROM 
	EMPLOYEES
WHERE 
	SALARY>=50000
OR
	DEPARTMENT = "IT";
    
    
SELECT
	*
FROM EMPLOYEES
WHERE NOT DEPARTMENT = "IT";



SELECT
	*
FROM 
	EMPLOYEES
WHERE
	SALARY>=50000
AND
	DEPARTMENT != "IT";
    
    
-- BETWEEN
-- SHOW THE REORDS WHERE SALARY IS IN BETWEEN 30000 TO 50000

SELECT
	*
FROM EMPLOYEES
WHERE SALARY 
BETWEEN 
	30000 AND 50000;
    
-- ALTERNATE QUERY
SELECT
	*
FROM EMPLOYEES
WHERE SALARY >=30000 AND SALARY<=50000;



-- SELECT EMPLOYEE THOSE COME FROM DELHI, MUMBAI, BENGALURUR

SELECT
	*
FROM EMPLOYEES
WHERE 
CITY = "DELHI" OR CITY = "MUMBAI" OR CITY ="BENGALURU";

SELECT
	*
FROM EMPLOYEES
WHERE CITY IN ("DELHI","MUMBAI","BENGALURU");

-- SELECT THE RECORDS WHERE EMPLOYEES SHOULD NOT COME FROM DELIH, MUMBAI, BENGALURU

SELECT
	*
FROM EMPLOYEES
WHERE CITY NOT IN ("DELHI","MUMBAI","BENGALURU");


-- LIKE OPERATOR

SELECT
	*
FROM EMPLOYEES
WHERE CITY LIKE 'JA%';

SELECT 
	*
FROM EMPLOYEES
WHERE CITY LIKE '%AI';


SELECT
	*
FROM EMPLOYEES
WHERE CITY LIKE '%GA%';

SELECT
	*
FROM EMPLOYEES
WHERE CITY LIKE '%GA__';

SELECT
	*
FROM EMPLOYEES
WHERE CITY LIKE '___GA%';


SELECT
	*
FROM EMPLOYEES
WHERE CITY NOT LIKE '___GA%';

-- IS NULL

SELECT
	*
FROM EMPLOYEES
WHERE SALARY IS NULL;

SELECT
	*
FROM EMPLOYEES
WHERE SALARY IS NOT NULL;

-- ORDER THE DATA

-- MIN -> MAX
SELECT 
	*
FROM EMPLOYEES
ORDER BY SALARY ASC;

-- MAX -> MIN
SELECT 
	*
FROM EMPLOYEES
ORDER BY SALARY DESC;


SELECT 
	*
FROM EMPLOYEES
ORDER BY CITY,SALARY;


-- LIMIT

-- TOP 10 HIGH PAID EMPLOYEES

SELECT 
	*
FROM EMPLOYEES
ORDER BY SALARY DESC
LIMIT 10;


-- AGGREGATION FUNCTIONS -> COUNT,SUM, AVG, MIN, MAX

SELECT
	SUM(SALARY) AS SALARY_POOL
FROM EMPLOYEES;


-- MAX PAID SALAYR BY COMPANY
SELECT
	MAX(SALARY)
FROM EMPLOYEES;

SELECT
	MIN(SALARY)
FROM EMPLOYEES;


SELECT
	AVG(SALARY)
FROM EMPLOYEES;